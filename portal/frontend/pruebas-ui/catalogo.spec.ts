import {test,expect} from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import type {Catalogo} from '../src/MvpTypes';
import type {EstadoInventario} from '../src/Alarmas';

// Primero se ejecuta contra Pruebas. Desarrollo se comprueba tras aplicar el mismo plan.
const entorno=process.env.MVP_CATALOGO_DESARROLLO==='1'?'Desarrollo':'Pruebas';
const base=entorno==='Pruebas'?'http://127.0.0.1:5088/':'http://127.0.0.1:5087/';
test('Catálogo documentado: procedencia, pendientes, nombres e Inventario; lectura sin cambios',async({page})=>{
 const acceso=JSON.parse(fs.readFileSync(path.resolve('../.local/acceso-inicial-Motherson_L1_MVP_'+entorno+'.json'),'utf8'));
 const errores:string[]=[];const escrituras:string[]=[];
 page.on('pageerror',e=>errores.push(e.message));
 page.on('request',r=>{if(r.method()==='POST'&&!r.url().includes('/auth/'))escrituras.push(r.url())});
 await page.goto(base);await page.getByLabel('Usuario',{exact:true}).fill(acceso.usuario);await page.getByLabel('Contraseña',{exact:true}).fill(acceso.password);
 const catalogoR=page.waitForResponse(r=>r.url().endsWith('/api/catalogo'));
 const inventarioR=page.waitForResponse(r=>r.url().includes('/inventario?alarmas=true'));
 await page.getByRole('button',{name:'Iniciar sesión'}).click();
 const catalogo:Catalogo=await(await catalogoR).json();const inventario:EstadoInventario=await(await inventarioR).json();
 expect(catalogo.atributos?.version).toBe(1);
 expect(catalogo.materiales.filter(m=>m.uso)).toHaveLength(62);
 expect(catalogo).not.toHaveProperty('colores');expect(catalogo.puestos.filter(p=>p.tipo)).toHaveLength(0);
 for(const m of catalogo.materiales.filter(m=>m.uso))expect(m.uso).toBe(catalogo.atributos?.materiales[m.numero_parte].uso.valor);
 for(const r of inventario.filas){const m=catalogo.materiales.find(m=>m.numero_parte===r.numero_parte)!;expect(r.uso).toBe(m.uso);expect(r).not.toHaveProperty('color')}
 await page.getByRole('navigation').getByRole('button',{name:'Materiales y catálogos',exact:true}).click();
 await expect(page.getByRole('region',{name:'Integridad del catálogo'})).toContainText(`62 de ${catalogo.materiales.length}`);
 const materiales=page.locator('section.panel').filter({has:page.getByRole('heading',{name:'Materiales',exact:true})});
 const puestos=page.locator('section.panel').filter({has:page.getByRole('heading',{name:'Puestos logísticos',exact:true})});
 await expect(materiales.getByRole('columnheader',{name:'Color',exact:true})).toHaveCount(0);
 await expect(puestos.getByRole('columnheader',{name:'Tipo',exact:true})).toHaveCount(0);
 const primero=catalogo.materiales.find(m=>m.uso)!;
 const fila=materiales.getByRole('row').filter({has:page.getByRole('cell',{name:primero.numero_parte,exact:true})});
 await expect(fila).toContainText(primero.uso!);await fila.getByText('Fuente del dato',{exact:true}).click();
 await expect(fila).toContainText('PFEP LOGISTICA - UPAEP (4).xlsx');
 await expect(fila).toContainText(catalogo.atributos!.materiales[primero.numero_parte].uso.fuente!.celda!);
 await expect(materiales.getByRole('row').filter({hasText:'57N 858 065 A MEC'})).toContainText('Pendiente de validación');
 for(const p of catalogo.puestos)await expect(puestos.getByRole('row').filter({has:page.getByRole('cell',{name:p.nombre,exact:true})})).toContainText(catalogo.atributos!.puestos[p.nombre].nombre);
 const dir=path.resolve('../evidencias/simplificacion/capturas',entorno.toLowerCase());fs.mkdirSync(dir,{recursive:true});
 await page.screenshot({path:path.join(dir,'01-catalogo-usos.png')});
 await page.getByRole('checkbox',{name:'Mostrar columnas sin datos'}).check();
 await expect(materiales.getByRole('columnheader',{name:'Color',exact:true})).toHaveCount(0);
 await expect(puestos.getByText('No documentado',{exact:true})).toHaveCount(6);
 await page.screenshot({path:path.join(dir,'02-catalogo-pendientes.png')});
 await puestos.scrollIntoViewIfNeeded();await page.screenshot({path:path.join(dir,'03-puestos.png')});
 await page.getByRole('navigation').getByRole('button',{name:'Inventario',exact:true}).click();
 await page.getByRole('textbox',{name:'Material',exact:true}).fill(primero.numero_parte);
 await expect(page.locator('tbody tr')).toContainText(primero.uso!);
 await expect(page.locator('tbody tr')).toContainText(catalogo.atributos!.puestos[primero.puesto].nombre);
 await expect(page.getByRole('columnheader',{name:'Color',exact:true})).toHaveCount(0);
 await page.screenshot({path:path.join(dir,'04-inventario.png')});
 await page.locator('.table-wrap').last().evaluate(el=>{el.scrollLeft=el.scrollWidth});
 await page.screenshot({path:path.join(dir,'04b-inventario-atributos.png')});
 const lectura=page.waitForResponse(r=>r.url().endsWith('/api/catalogo'));await page.getByRole('button',{name:'Actualizar',exact:true}).click();
 const nuevo:Catalogo=await(await lectura).json();expect(nuevo.materiales).toEqual(catalogo.materiales);
 await page.setViewportSize({width:390,height:844});await page.getByLabel('Sección',{exact:true}).selectOption('1');
 await expect(materiales).toBeVisible();expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:path.join(dir,'05-catalogo-movil.png')});
 expect(escrituras).toEqual([]);expect(errores).toEqual([]);
});
